-- OpenDoor Living Supabase schema.
-- Run in Supabase SQL Editor. Public users can read active homes only; all inquiry reads/updates are admin-only.

create extension if not exists pgcrypto;

create table if not exists public.listings (
  id bigint generated by default as identity primary key,
  title text not null,
  location text not null,
  full_location text not null,
  price integer not null check (price between 1 and 100000),
  type text not null,
  beds integer not null check (beds between 0 and 20),
  baths numeric(3,1) not null default 1 check (baths >= 0),
  sqft integer not null default 0 check (sqft >= 0),
  image text not null,
  images jsonb not null default '[]'::jsonb,
  badge text not null default 'Available',
  features jsonb not null default '[]'::jsonb,
  description text not null default '',
  available text not null default 'Contact for availability',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inquiries (
  id uuid primary key default gen_random_uuid(),
  listing_id bigint not null references public.listings(id) on delete restrict,
  name text not null check (char_length(name) between 1 and 120),
  email text not null check (char_length(email) <= 254),
  phone text check (phone is null or char_length(phone) <= 40),
  request_type text not null check (request_type in ('Tour request', 'Rental application inquiry', 'Ask a question')),
  preferred_date date,
  offer integer not null check (offer between 500 and 10000),
  message text check (message is null or char_length(message) <= 2000),
  status text not null default 'new' check (status in ('new', 'contacted', 'tour_scheduled', 'approved', 'rejected', 'closed')),
  created_at timestamptz not null default now()
);

create index if not exists inquiries_created_at_idx on public.inquiries (created_at desc);
create index if not exists inquiries_status_idx on public.inquiries (status);
create index if not exists listings_location_price_idx on public.listings (location, price) where is_active = true;

alter table public.listings enable row level security;
alter table public.inquiries enable row level security;

drop policy if exists "Public can view active listings" on public.listings;
create policy "Public can view active listings" on public.listings for select to anon, authenticated using (is_active = true);

-- Do not create public inquiry policies. Public requests are validated and inserted by the server API.
-- Admin reads/updates use the server-only service role after the server verifies a Supabase Auth JWT
-- and app_metadata.role = 'admin'. Never use the service-role key in the browser.

